-- Monitoring and command queue for authenticated RFID devices.
-- Apply only after reviewing the deployment's existing migration state.

CREATE TABLE IF NOT EXISTS public.iot_devices (
  id VARCHAR(80) PRIMARY KEY,
  name VARCHAR(120) NOT NULL DEFAULT 'RFID SiPresensi',
  last_seen_at TIMESTAMPTZ,
  offline_reported_at TIMESTAMPTZ,
  wifi_connected BOOLEAN,
  wifi_ssid VARCHAR(120),
  ip_address VARCHAR(64),
  rssi SMALLINT,
  rfid_initialized BOOLEAN,
  rfid_connected BOOLEAN,
  last_uid VARCHAR(80),
  last_card_at TIMESTAMPTZ,
  last_error TEXT,
  last_error_at TIMESTAMPTZ,
  firmware_version VARCHAR(80),
  last_restart_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.iot_device_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_id VARCHAR(80) NOT NULL REFERENCES public.iot_devices(id) ON DELETE CASCADE,
  event_type VARCHAR(40) NOT NULL CHECK (event_type IN (
    'device_connected',
    'device_disconnected',
    'wifi_changed',
    'rfid_card_read',
    'rfid_error',
    'device_error',
    'restart_requested',
    'restart_acknowledged',
    'restarted'
  )),
  details JSONB NOT NULL DEFAULT '{}'::JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.iot_device_commands (
  id VARCHAR(80) PRIMARY KEY,
  device_id VARCHAR(80) NOT NULL REFERENCES public.iot_devices(id) ON DELETE CASCADE,
  command VARCHAR(40) NOT NULL CHECK (command = 'restart'),
  status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (status IN (
    'pending', 'acknowledged', 'completed', 'failed', 'expired'
  )),
  requested_by VARCHAR(80) NOT NULL,
  requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  expires_at TIMESTAMPTZ NOT NULL,
  acknowledged_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ,
  error TEXT
);

CREATE INDEX IF NOT EXISTS iot_device_events_device_created_idx
  ON public.iot_device_events(device_id, created_at DESC);
CREATE INDEX IF NOT EXISTS iot_device_commands_pending_idx
  ON public.iot_device_commands(device_id, status, requested_at);

ALTER TABLE public.iot_devices ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.iot_device_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.iot_device_commands ENABLE ROW LEVEL SECURITY;
